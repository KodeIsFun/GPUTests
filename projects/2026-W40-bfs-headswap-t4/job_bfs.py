LORA_MAP = {"pruna8": LORA_PRUNA8, "bfs_head": BFS_HEAD, "bfs_body": BFS_BODY}
CACHE_DEFAULTS = {}  # filled from /object_info in preflight
LATENT_OUT_IDX = 2  # corrected in preflight from te_output_names


def bfs_swap(scene_file, head_file, latent_wh, scene_size, ref_size, prefix, sampler,
             loras=(("stock:pruna8", 1.0), ("stock:bfs_head", 1.0)), dit="int8",
             use_cache=True, latent_from_te=False, prompt=HEAD_PROMPT, te_resolution=0,
             warm_crop=False):
    """BFS two-image swap, mirroring the official workflow:
    DiT -> LoraLoaderModelOnly(Pruna8) -> LoraLoaderModelOnly(BFS) -> QwenImage21Cache
    -> KSampler(deis_2m, 8 steps, cfg 1.0) <- TextEncodeQwenImage21(clip, vae, images).
    refs pre-scaled (lanczos): scene to scene_size, head/ref to ref_size; TE
    resolution 0 = refs at own size (the template's own combination). LoRA spec
    keys 'stock:<name>' use the stock merge (author-faithful); 'hook:<name>'
    load through the viggle runtime-hook node (exact update on quantized weights)."""
    g = {}
    if dit == "int8":
        g["1"] = {"class_type": "UNETLoader",
                  "inputs": {"unet_name": DIT_INT8_NAME, "weight_dtype": "default"}}
    else:
        g["1"] = {"class_type": "UnetLoaderGGUF", "inputs": {"unet_name": GGUF_NAME}}
    g["2"] = {"class_type": "CLIPLoader", "inputs": {"clip_name": TE_NAME, "type": "qwen_image"}}
    g["3"] = {"class_type": "VAELoader", "inputs": {"vae_name": VAE_NAME}}
    g["10"] = {"class_type": "LoadImage", "inputs": {"image": scene_file}}
    g["11"] = {"class_type": "LoadImage", "inputs": {"image": head_file}}
    g["12"] = {"class_type": "ImageScale",
               "inputs": {"upscale_method": "lanczos", "width": scene_size,
                          "height": scene_size,
                          "crop": "center" if warm_crop else "disabled",
                          "image": ["10", 0]}}
    g["13"] = {"class_type": "ImageScale",
               "inputs": {"upscale_method": "lanczos", "width": ref_size,
                          "height": ref_size, "crop": "disabled", "image": ["11", 0]}}
    model_src = "1"
    n = 20
    for name, strength in loras:
        key = name.split(":", 1)[1]
        lora = LORA_MAP[key]
        if name.startswith("hook:"):
            g[str(n)] = {"class_type": "ViggleTurboLora",
                         "inputs": {"model": [model_src, 0], "lora_name": lora,
                                    "strength": strength}}
        else:
            g[str(n)] = {"class_type": "LoraLoaderModelOnly",
                         "inputs": {"model": [model_src, 0], "lora_name": lora,
                                    "strength_model": strength}}
        model_src = str(n)
        n += 1
    if use_cache:
        g[str(n)] = {"class_type": "QwenImage21Cache",
                     "inputs": {"model": [model_src, 0], **CACHE_DEFAULTS}}
        model_src = str(n)
        n += 1
    g["30"] = {"class_type": "TextEncodeQwenImage21",
               "inputs": {"clip": ["2", 0], "vae": ["3", 0], "prompt": prompt,
                          "negative_prompt": "", "resolution": te_resolution,
                          "images": {"image_1": ["12", 0], "image_2": ["13", 0]}}}
    if latent_from_te:
        latent_src = ["30", LATENT_OUT_IDX]
    else:
        g["31"] = {"class_type": "EmptyLatentImage",
                   "inputs": {"width": latent_wh, "height": latent_wh, "batch_size": 1}}
        latent_src = ["31", 0]
    g["32"] = {"class_type": "KSampler",
               "inputs": {"model": [model_src, 0], "positive": ["30", 0],
                          "negative": ["30", 1], "latent_image": latent_src,
                          "seed": SEED, "steps": 8, "cfg": 1.0,
                          "sampler_name": sampler, "scheduler": "simple", "denoise": 1.0}}
    g["33"] = {"class_type": "VAEDecode", "inputs": {"samples": ["32", 0], "vae": ["3", 0]}}
    g["34"] = {"class_type": "SaveImage", "inputs": {"images": ["33", 0],
                                                     "filename_prefix": prefix}}
    return g


