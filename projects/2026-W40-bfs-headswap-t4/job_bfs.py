def http_json(path, payload=None, timeout=60):
    if payload is not None:
        req = urllib.request.Request(BASE + path, data=json.dumps(payload).encode(), method="POST",
                                     headers={"Content-Type": "application/json"})
    else:
        req = urllib.request.Request(BASE + path, method="GET")
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def wait_server(proc, timeout=300):
    t0 = time.time()
    while time.time() - t0 < timeout:
        if proc.poll() is not None:
            return False
        try:
            http_json("/system_stats", timeout=5)
            return True
        except Exception:
            time.sleep(3)
    return False


BOOT_N = 0
COMFY_LOG_PATH = None


def boot_server():
    """Boot (or reboot) ComfyUI; returns the process. Reboot frees RAM between blocks.
    Kills any zombie server first — run-1 lesson: a script exit without finally
    left boot-1 alive on 8188, the new server died at bind, and the zombie's
    /object_info answered preflight while render() watched the dead process."""
    global proc, BOOT_N, COMFY_LOG_PATH
    subprocess.run("pkill -f 'main.py --listen 127.0.0.1 --port 8188' || true", shell=True)
    time.sleep(3)
    BOOT_N += 1
    COMFY_LOG_PATH = f"{OUT}/comfyui-b{BOOT_N}.log"
    log(f"booting server (boot {BOOT_N}) with {FLAGS}")
    comfy_log = open(COMFY_LOG_PATH, "w")
    proc = subprocess.Popen([sys.executable, "main.py", "--listen", "127.0.0.1",
                             "--port", str(PORT), *FLAGS],
                            cwd=C, stdout=comfy_log, stderr=subprocess.STDOUT)
    if not wait_server(proc):
        tail = subprocess.run(f"tail -30 {COMFY_LOG_PATH}", shell=True,
                              capture_output=True, text=True).stdout
        log(f"BOOT FAILED:\n{tail}")
        sys.exit(2)
    TIM[f"boot{BOOT_N}_s"] = round(time.time() - T0, 1)
    save()
    atexit.register(_kill_server)
    return proc


def _kill_server():
    p = globals().get("proc")
    if p is not None and p.poll() is None:
        p.terminate()
        try:
            p.wait(10)
        except subprocess.TimeoutExpired:
            p.kill()


def preflight():
    """Self-diagnosing node check (v1 lesson: fail in 5s with the enum list, not
    after a 30-min image). Records every enum the ladders depend on."""
    oi = http_json("/object_info", timeout=120)
    req_nodes = ["UNETLoader", "UnetLoaderGGUF", "CLIPLoader", "VAELoader",
                 "LoraLoaderModelOnly", "TextEncodeQwenImage21", "QwenImage21Cache",
                 "EmptyLatentImage", "KSampler", "VAEDecode", "SaveImage", "LoadImage",
                 "ImageScale", "ViggleTurboLora", "ViggleTurboSigmas"]
    missing = [n for n in req_nodes if n not in oi]
    pf = {"missing_nodes": missing, "n_classes": len(oi)}
    if missing:
        sys.exit(f"PREFLIGHT FAIL — missing {missing}; classes sample: "
                 f"{sorted(oi)[:40]}")
    clipl = oi["CLIPLoader"]["input"]["required"]
    pf["clip_types"] = clipl["type"][0] if "type" in clipl else None
    assert "qwen_image" in pf["clip_types"], f"qwen_image not in CLIPLoader types {pf['clip_types']}"
    samplers = oi["KSampler"]["input"]["required"]["sampler_name"][0]
    pf["sampler_available"] = [s for s in SAMPLER_LADDER if s in samplers]
    assert pf["sampler_available"], f"none of {SAMPLER_LADDER} in KSampler enum"
    te = oi["TextEncodeQwenImage21"]
    pf["te_outputs"] = te.get("output", [])
    pf["te_output_names"] = te.get("output_name", [])
    pf["te_inputs"] = sorted(set(list(te["input"].get("required", {})) +
                                 list(te["input"].get("optional", {}))))
    qc = oi["QwenImage21Cache"]
    qc_in = {**qc["input"].get("required", {}), **qc["input"].get("optional", {})}
    # attempt-1 lesson: device/dtype are REQUIRED in API format — pull defaults
    # from the [type, {default: ...}] config shape ('auto'/'default', the author's
    # own widget values); bare [type, default] shapes also handled.
    pf["cache_inputs"] = {}
    for k, v in qc_in.items():
        if isinstance(v, list) and len(v) > 1 and isinstance(v[1], dict):
            pf["cache_inputs"][k] = v[1].get("default", v[1])
        else:
            pf["cache_inputs"][k] = v
    CACHE_DEFAULTS.clear()
    CACHE_DEFAULTS.update({k: v for k, v in pf["cache_inputs"].items()
                           if k != "model" and not isinstance(v, (list, dict))})
    ims = oi["ImageScale"]["input"]
    pf["imagescale_inputs"] = sorted(set(list(ims.get("required", {})) +
                                         list(ims.get("optional", {}))))
    TIM["preflight"] = pf
    save()
    log(f"preflight OK: sampler={pf['sampler_available'][0]} "
        f"te_outputs={pf['te_outputs']} te_inputs={pf['te_inputs']}")
    return pf


