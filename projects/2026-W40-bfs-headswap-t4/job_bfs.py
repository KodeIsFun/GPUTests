def ssim_gray(a_path, b_path, bottom_frac=None, size=256):
    """Coarse block-SSIM on grayscale; lower = more drift. bottom_frac crops to
    the lower part of the frame (below the head) before resize."""
    from PIL import Image
    import numpy as np
    def prep(p):
        im = Image.open(p).convert("L")
        w, h = im.size
        if bottom_frac:
            im = im.crop((0, int(h * (1 - bottom_frac)), w, h))
        return np.asarray(im.resize((size, size), Image.LANCZOS), dtype=np.float64) / 255.0
    a, b = prep(a_path), prep(b_path)
    C1, C2, win = (0.01) ** 2, (0.03) ** 2, 8
    m = size // win
    ba, bb = a.reshape(m, win, m, win), b.reshape(m, win, m, win)
    a, b = ba.mean(axis=(1, 3)), bb.mean(axis=(1, 3))
    va, vb = ba.var(axis=(1, 3)), bb.var(axis=(1, 3))
    cov = (ba * bb).mean(axis=(1, 3)) - a * b
    s = ((2 * a * b + C1) * (2 * cov + C2)) / ((a * a + b * b + C1) * (va + vb + C2))
    return round(float(s.mean()), 4)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:16]


def face_model():
    """Best-effort ArcFace via insightface (CPU). Returns embed fn or None."""
    try:
        from PIL import Image
        import numpy as np
        from insightface.app import FaceAnalysis
        app = FaceAnalysis(name="buffalo_l", providers=["CPUExecutionProvider"])
        app.prepare(ctx_id=-1, det_size=(640, 640))

        def embed(path):
            img = np.asarray(Image.open(path).convert("RGB"))[:, :, ::-1]
            faces = app.get(img)
            if not faces:
                return None
            f = max(faces, key=lambda x: (x.bbox[2] - x.bbox[0]) * (x.bbox[3] - x.bbox[1]))
            return f.normed_embedding
        return embed
    except Exception as e:
        log(f"insightface unavailable: {type(e).__name__}: {e}")
        return None


def evaluate():
    """Identity sims (if ArcFace available) + background SSIM per swap output."""
    ev = TIM.setdefault("eval", {})
    from PIL import Image  # noqa
    scene_png = next((f"{OUT}/{r['files'][0]}" for r in TIM["rows"]
                      if r.get("ok") and r["files"] and r["key"] == "gen_in_scene"), None)
    head_png = next((f"{OUT}/{r['files'][0]}" for r in TIM["rows"]
                     if r.get("ok") and r["files"] and r["key"] == "gen_in_head"), None)
    if scene_png and head_png:
        for r in TIM["rows"]:
            if not (r.get("ok") and r.get("files")):
                continue
            out = f"{OUT}/{r['files'][0]}"
            if r["key"] == "gen_in_scene":
                continue
            ev.setdefault("bg_ssim", {})[r["key"]] = {
                "full": ssim_gray(out, scene_png),
                "bottom45": ssim_gray(out, scene_png, bottom_frac=0.45),
            }
        ev["canary_note"] = ("FREE GPU LAB neon legibility eyeballed from committed PNGs; "
                             "see README. SSIM here is quantitative background drift only.")
        embed = None
        try:
            r = subprocess.run(["pip", "install", "-q", "insightface", "onnxruntime"],
                               capture_output=True, text=True, timeout=420)
            log(f"pip insightface rc={r.returncode}")
            embed = face_model()
        except Exception as e:
            log(f"insightface install failed: {e}")
        ev["arcface"] = {"available": embed is not None}
        if embed:
            import numpy as np
            e_scene, e_head = embed(scene_png), embed(head_png)
            sims = {}
            for r in TIM["rows"]:
                if not (r.get("ok") and r.get("files")) or r["key"] == "gen_in_scene":
                    continue
                e = embed(f"{OUT}/{r['files'][0]}")
                if e is None or e_scene is None or e_head is None:
                    sims[r["key"]] = {"face_detected": e is not None}
                    continue
                sims[r["key"]] = {
                    "sim_vs_refhead": round(float(np.dot(e, e_head)), 4),
                    "sim_vs_sceneperson": round(float(np.dot(e, e_scene)), 4),
                }
            ev["arcface"]["rows"] = sims
            ev["arcface"]["note"] = ("sim_vs_refhead should rise on BFS rows (identity "
                                     "transferred) and stay low on the anchor; "
                                     "sim_vs_sceneperson the reverse. 1.0 = identical.")
    for r in TIM["rows"]:
        if r.get("files"):
            r["sha256"] = {fn: sha256(f"{OUT}/{fn}") for fn in r["files"]}
    save()


