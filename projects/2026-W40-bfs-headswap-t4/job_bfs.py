def submit(graph):
    """POST /prompt with ladders; returns (prompt_id, None) or (None, error_str).
    Autogrow images API format = FLAT dotted keys ('images.image_1') — the
    server's _resolve_dynamic_paths pops those keys and nests them itself.
    Attempt-2 lesson: a nested dict {'images': {...}} validates AND executes
    silently with zero images bound (all swap rows became pure t2i), so flat
    goes first and the nested form is only a fallback."""
    for fmt, mutate in (
        ("flat", lambda gg: _flatten_autogrow(gg)),
        ("nested", lambda gg: gg),
    ):
        gg = json.loads(json.dumps(mutate(graph)))
        try:
            r = http_json("/prompt", {"prompt": gg, "client_id": "w40bfs"}, timeout=120)
            return r["prompt_id"], None
        except urllib.error.HTTPError as e:
            body = e.read().decode(errors="replace")
            log(f"submit rejected ({fmt}): {body[:300]}")
            if fmt == "flat" and "image" in body:
                continue
            return None, body[:800]
        except Exception as e:
            return None, f"{type(e).__name__}: {e}"
    return None, "submit exhausted"


def _flatten_autogrow(graph):
    for node in graph.values():
        imgs = node.get("inputs", {}).get("images")
        if isinstance(imgs, dict):
            for k, v in imgs.items():
                node["inputs"][f"images.{k}"] = v
            del node["inputs"]["images"]
    return graph


def comfy_vram():
    try:
        st = http_json("/system_stats", timeout=10)
        dev = st.get("devices", [{}])[0]
        return {"vram_free_gb": round(dev.get("vram_free", 0) / 1e9, 2),
                "vram_total_gb": round(dev.get("vram_total", 0) / 1e9, 2)}
    except Exception:
        return {}


def ram_gb():
    try:
        with open("/proc/meminfo") as f:
            info = {l.split(":")[0]: int(l.split()[1]) for l in f if ":" in l}
        return round((info["MemTotal"] - info["MemAvailable"]) / 1e6, 2)
    except Exception:
        return None


def render(name, graph, comfy_log_path, poll_s=1800, meta=None):
    """Run one graph to completion; download PNGs; record wall/stats."""
    h = hashlib.md5(json.dumps(graph, sort_keys=True).encode()).hexdigest()
    assert h not in _seen_graph_hashes, f"graph for {name} duplicates an earlier row (cache-hit risk)"
    _seen_graph_hashes.add(h)
    rec = {"key": name, "graph_md5": h, "meta": meta or {},
           "ram_used_gb": ram_gb(), **comfy_vram()}
    t0 = time.time()
    pid, err = submit(graph)
    if pid is None:
        rec.update({"ok": False, "wall_s": round(time.time() - t0, 1), "note": f"submit: {err}"})
        TIM["rows"].append(rec)
        save()
        return rec
    ok, imgs, note = False, [], ""
    while time.time() - t0 < poll_s:
        time.sleep(3)
        if proc.poll() is not None:
            note = "server process died"
            break
        try:
            hist = http_json(f"/history/{pid}", timeout=15)
        except Exception:
            continue
        if pid not in hist:
            continue
        entry = hist[pid]
        status = entry.get("status", {})
        imgs = [im["filename"] for o in entry.get("outputs", {}).values()
                for im in o.get("images", [])]
        if status.get("status_str") == "error":
            msgs = json.dumps(status.get("messages", []))
            note = f"comfy error: {msgs[:400]}"
            break
        if imgs:
            ok, note = True, "ok"
            break
    rec.update({"ok": ok, "wall_s": round(time.time() - t0, 1), "note": note, "files": imgs})
    log(f"{name}: ok={ok} {rec['wall_s']}s ({note[:120]})")
    if ok:
        saved = []
        for fn in imgs:
            data = urllib.request.urlopen(
                f"{BASE}/view?filename={urlquote(fn)}&subfolder=&type=output",
                timeout=120).read()
            dest = f"{OUT}/{fn}"
            with open(dest, "wb") as f:
                f.write(data)
            saved.append(fn)
        rec["saved"] = saved
        rec.update(post_render_stats(comfy_log_path))
        rec["ram_used_gb_after"] = ram_gb()
        rec.update(comfy_vram())
    TIM["rows"].append(rec)
    save()
    return rec


def post_render_stats(comfy_log_path):
    rec = {}
    try:
        logtxt = open(comfy_log_path).read()
        it_lines = re.findall(r"(\d+)/(\d+) \[[0-9:]+<[0-9:]+, +([0-9.]+)s/it", logtxt)
        rec["s_per_step"] = it_lines[-1][2] if it_lines else None
        ex = re.findall(r"Prompt executed in ([0-9:.]+)", logtxt)
        rec["executed_s"] = ex[-1] if ex else None
    except Exception:
        pass
    return rec


def swap_inputs_to_input_dir(rec, name):
    """Copy a generated input PNG from ComfyUI/output to ComfyUI/input for LoadImage."""
    fn = rec["files"][0]
    src = f"{C}/output/{fn}"
    dst = f"{C}/input/{name}.png"
    subprocess.run(["cp", src, dst], check=True)
    return f"{name}.png"


